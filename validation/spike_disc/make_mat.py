"""Spike: write the openCFS material XML for PZT-4 from the d-form library entry.

Losses as complex coefficients (e^{jwt} convention assumed, verified by Re(Y) > 0 in the run):
    c = c^E (1 + j/Qm),  eps = eps^S (1 - j tan_delta),  e real.
"""

import sys

import numpy as np

sys.path.insert(0, "/app")
from app.materials.convert import eform_from_library, load_library_material  # noqa: E402


def fmt(m: np.ndarray) -> str:
    return "\n".join("            " + " ".join(f"{v: .6e}" for v in row) for row in m)


def tensor(name: str, real: np.ndarray, imag: np.ndarray | None) -> str:
    rows, cols = real.shape
    out = f'<tensor dim1="{rows}" dim2="{cols}">\n          <real>\n{fmt(real)}\n          </real>\n'
    if imag is not None:
        out += f"          <imag>\n{fmt(imag)}\n          </imag>\n"
    return out + "        </tensor>"


def main(material_id: str, path: str, lossless: bool) -> None:
    m = eform_from_library(material_id)
    losses = load_library_material(material_id)["losses"]
    c_imag = None if lossless else m.c_E / losses["Qm"]
    eps_imag = None if lossless else -m.eps_S * losses["tan_delta"]
    xml = f"""<?xml version='1.0' encoding='utf-8'?>
<cfsMaterialDataBase xmlns="http://www.cfs++.org/material">
  <!-- Generated by make_mat.py from library/{material_id}.json (IEEE Voigt, poling along 3).
       openCFS rejects comments outside the root element. -->
  <material name="{material_id}">
    <mechanical>
      <density><linear><real>{m.density:.6e}</real></linear></density>
      <elasticity><linear>
        {tensor("c", m.c_E, c_imag)}
      </linear></elasticity>
    </mechanical>
    <electric>
      <permittivity><linear>
        {tensor("eps", m.eps_S, eps_imag)}
      </linear></permittivity>
    </electric>
    <piezo>
      <piezoCoupling><linear>
        {tensor("e", m.e, None)}
      </linear></piezoCoupling>
    </piezo>
  </material>
</cfsMaterialDataBase>
"""
    with open(path, "w") as f:
        f.write(xml)
    print(f"wrote {path} ({'lossless' if lossless else 'lossy'})")


if __name__ == "__main__":
    main("PZT-4", sys.argv[1], lossless="--lossless" in sys.argv)
